/**
 * Copies the engine into the extension so the content script and the CLI
 * share one source of truth. No bundler: the modules are plain ESM and the
 * content script loads them with a dynamic import of a web-accessible URL.
 *
 * panel.css gets the same treatment, wrapped as a module. The content script
 * needs the stylesheet as *text* so it can put it inside the panel's shadow
 * root, and the obvious way to get it — fetch(runtime.getURL('panel.css')) —
 * would put the identifier `fetch` into the shipped extension. That costs more
 * than it is worth: "no file in the extension mentions a network API" is a
 * guarantee a three-line test can check and a reviewer can verify by eye,
 * and an import keeps it true.
 */
import { mkdirSync, readdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'extension', 'engine');
mkdirSync(out, { recursive: true });

let n = 0;
for (const file of readdirSync(join(root, 'src'))) {
  if (!file.endsWith('.js')) continue;
  copyFileSync(join(root, 'src', file), join(out, file));
  n++;
}

const css = readFileSync(join(root, 'extension', 'panel.css'), 'utf8');
writeFileSync(
  join(out, 'panel.css.js'),
  '// Generated by scripts/build-extension.js from extension/panel.css.\n'
  + '// Edit the stylesheet, not this file.\n'
  + 'export default ' + JSON.stringify(css) + ';\n',
);

console.log(`chhanni: copied ${n} engine modules and the panel stylesheet into extension/engine/`);
